#[test]
fn environment_child() {
    let Ok(root) = std::env::var("PITCREW_SETUP_TEST_ROOT") else {
        return;
    };
    let (mut flags, output) = fixture(Path::new(&root));
    for (flag, env_flag, variable) in [
        (
            "--plex-token-file",
            "--plex-token-env",
            "PITCREW_SETUP_TEST_TOKEN",
        ),
        (
            "--arr-api-key-file",
            "--arr-api-key-env",
            "PITCREW_SETUP_TEST_KEY",
        ),
    ] {
        let index = flags.iter().position(|value| value == flag).unwrap();
        flags[index] = env_flag.into();
        flags[index + 1] = variable.into();
    }
    let result = pitcrew_setup::create(options(&flags), &mut empty());
    if std::env::var_os("PITCREW_SETUP_TEST_KEY").is_none() {
        assert_eq!(
            result.err().unwrap(),
            "init: credential environment variable absent or not UTF-8"
        );
        assert!(!output.exists());
    } else {
        let config = result.unwrap().local_config;
        assert_eq!(
            config
                .plex
                .unwrap()
                .owner_token
                .resolve("plex")
                .unwrap()
                .expose(),
            "env-token"
        );
        assert_eq!(
            config.arr[0].api_key.resolve("arr").unwrap().expose(),
            "env-key"
        );
    }
}

#[test]
fn environment_credentials_resolve_without_changing_the_parent_environment() {
    for missing in [true, false] {
        let temp = tempfile::tempdir().unwrap();
        let mut command = std::process::Command::new(std::env::current_exe().unwrap());
        command
            .args(["--exact", "environment_child", "--nocapture"])
            .env("PITCREW_SETUP_TEST_ROOT", temp.path())
            .env("PITCREW_SETUP_TEST_TOKEN", "env-token\n")
            .env_remove("PITCREW_SETUP_TEST_KEY");
        if !missing {
            command.env("PITCREW_SETUP_TEST_KEY", "env-key");
        }
        assert!(command.status().unwrap().success());
    }
}

#[test]
fn plex_path_prefixes_are_rejected_before_writes_but_arr_prefixes_are_supported() {
    let temp = tempfile::tempdir().unwrap();
    let (base, output) = fixture(temp.path());
    for url in [
        "https://plex.example.invalid/plex",
        "https://plex.example.invalid/plex/",
        "https://plex.example.invalid/%2F",
    ] {
        let mut flags = base.clone();
        let plex = flags
            .iter()
            .position(|value| value == "--plex-url")
            .unwrap();
        flags[plex + 1] = url.into();
        assert_eq!(
            pitcrew_setup::create(options(&flags), &mut empty()).err(),
            Some("init: Plex URL must use the server root without a path prefix")
        );
        assert!(!output.exists());
    }
    let mut flags = base;
    let arr = flags.iter().position(|value| value == "--arr-url").unwrap();
    flags[arr + 1] = "https://arr.example.invalid/sonarr/".into();
    let config = pitcrew_setup::create(options(&flags), &mut empty())
        .unwrap()
        .local_config;
    assert_eq!(config.arr[0].url, "https://arr.example.invalid/sonarr/");
}

struct FakeServer {
    calls: usize,
    seen_token: Option<String>,
    result: pitcrew_setup::Result<()>,
}
impl pitcrew_setup::Discover for FakeServer {
    fn discover(
        &mut self,
        _plex_url: &str,
        token: &str,
    ) -> pitcrew_setup::Result<pitcrew_setup::Server> {
        self.calls += 1;
        self.seen_token = Some(token.into());
        self.result?;
        Ok(pitcrew_setup::Server {
            id: "discovered-server".into(),
            sections: vec![
                pitcrew_setup::Section {
                    key: "3".into(),
                    kind: "movie".into(),
                    title: "Films\u{1b}[2J".into(),
                },
                pitcrew_setup::Section {
                    key: "9".into(),
                    kind: "show".into(),
                    title: "Shows".into(),
                },
            ],
        })
    }
}
fn fake_server() -> FakeServer {
    FakeServer {
        calls: 0,
        seen_token: None,
        result: Ok(()),
    }
}

/// The fixture minus `--plex-server-id` and `--library`, plus `--discover`.
fn discover_flags(flags: &[String], library: Option<&str>) -> Vec<String> {
    let mut out = vec!["--discover".to_string()];
    let mut it = flags.iter();
    while let Some(flag) = it.next() {
        if flag == "--plex-server-id" || flag == "--library" {
            it.next();
        } else {
            out.push(flag.clone());
        }
    }
    if let Some(library) = library {
        out.extend(["--library".to_string(), library.to_string()]);
    }
    out
}

#[test]
fn discover_fills_server_id_and_checks_library_against_the_server() {
    let temp = tempfile::tempdir().unwrap();
    let (flags, output) = fixture(temp.path());
    let mut server = fake_server();
    pitcrew_setup::create_with(
        options(&discover_flags(&flags, Some("9"))),
        &mut empty(),
        &mut server,
    )
    .unwrap();
    assert_eq!(server.calls, 1);
    assert_eq!(server.seen_token.as_deref(), Some("synthetic-plex-token"));
    let config = Config::parse(&fs::read_to_string(output.join("pitcrew.toml")).unwrap()).unwrap();
    assert_eq!(config.plex.unwrap().server_id, "discovered-server");
    // The token read once for discovery is the one saved.
    assert_eq!(
        fs::read_to_string(output.join("secrets/plex-token")).unwrap(),
        "synthetic-plex-token"
    );
}

#[test]
fn discover_rejects_unknown_library_and_mismatched_server_id_before_writing() {
    let temp = tempfile::tempdir().unwrap();
    let (flags, output) = fixture(temp.path());
    let unknown = pitcrew_setup::create_with(
        options(&discover_flags(&flags, Some("7"))),
        &mut empty(),
        &mut fake_server(),
    );
    assert_eq!(
        unknown.err(),
        Some("init: library key is not a section on the discovered server")
    );
    let mut mismatched = discover_flags(&flags, Some("9"));
    mismatched.extend(["--plex-server-id".into(), "other-server".into()]);
    let result = pitcrew_setup::create_with(options(&mismatched), &mut empty(), &mut fake_server());
    assert_eq!(
        result.err(),
        Some("init: --plex-server-id does not match the discovered server")
    );
    let mut matching = discover_flags(&flags, Some("3"));
    matching.extend(["--plex-server-id".into(), "discovered-server".into()]);
    pitcrew_setup::create_with(options(&matching), &mut empty(), &mut fake_server()).unwrap();
    assert!(output.join("pitcrew.toml").exists());
}

