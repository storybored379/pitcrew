use pitcrew_config::{ArrKind, Config, EngineMode};
use pitcrew_setup::{Options, Prompt};
use std::{
    collections::VecDeque,
    fs,
    os::unix::fs::PermissionsExt,
    path::{Path, PathBuf},
};

struct Inputs(VecDeque<(String, bool)>);
impl Prompt for Inputs {
    fn read(&mut self, _label: &str, secret: bool) -> pitcrew_setup::Result<String> {
        let (value, expected_secret) = self.0.pop_front().expect("unexpected prompt");
        assert_eq!(secret, expected_secret);
        Ok(value)
    }
}

fn args(values: &[&str]) -> Vec<String> {
    values.iter().map(|value| (*value).into()).collect()
}
fn options(values: &[String]) -> Options {
    Options::parse(values).unwrap().unwrap()
}
fn fixture(root: &Path) -> (Vec<String>, PathBuf) {
    let output = root.join("installation");
    let token = root.join("token-input");
    let key = root.join("key-input");
    fs::write(&token, "synthetic-plex-token\r\n").unwrap();
    fs::write(&key, "synthetic-arr-key\n").unwrap();
    (
        args(&[
            "--non-interactive",
            "--output",
            output.to_str().unwrap(),
            "--plex-url",
            "http://plex.example.invalid:32400",
            "--plex-server-id",
            "synthetic-server",
            "--plex-token-file",
            token.to_str().unwrap(),
            "--arr-kind",
            "sonarr",
            "--arr-url",
            "http://sonarr.example.invalid:8989",
            "--arr-api-key-file",
            key.to_str().unwrap(),
            "--library",
            "7",
        ]),
        output,
    )
}

fn empty() -> Inputs {
    Inputs(VecDeque::new())
}

#[test]
fn noninteractive_creates_minimum_shadow_install_with_private_files() {
    let temp = tempfile::tempdir().unwrap();
    let (flags, output) = fixture(temp.path());
    let install = pitcrew_setup::create(options(&flags), &mut empty()).unwrap();
    assert!(!install.connectivity);
    let source = fs::read_to_string(output.join("pitcrew.toml")).unwrap();
    assert!(source.starts_with("# Generated by pitcrew init."));
    assert!(source.contains("# Optional extras"));
    assert!(!source.contains("synthetic-plex-token"));
    assert!(!source.contains("synthetic-arr-key"));
    let config = Config::parse(&source).unwrap();
    assert_eq!(config.database, output.join("state/pitcrew.sqlite"));
    assert_eq!(
        config.stack.intake_database,
        output.join("state/intake.sqlite")
    );
    assert_eq!(
        config.stack.catalog_snapshot_file,
        Some(output.join("state/catalog.json"))
    );
    assert_eq!(config.engine.mode, EngineMode::Shadow);
    assert!(!config.engine.acknowledge_live_mutations);
    assert!(!config.engine.poll_enabled);
    assert_eq!(config.engine.listen.to_string(), "127.0.0.1:7400");
    assert!(config.stack.enabled);
    assert_eq!(config.stack.web_listen.to_string(), "127.0.0.1:7401");
    assert_eq!(config.stack.web_public_origin, "http://127.0.0.1:7401");
    assert_eq!(config.providers.decider, pitcrew_config::Decider::Rules);
    assert_eq!(
        config.providers.reply_writer,
        pitcrew_config::ReplyWriter::Templates
    );
    assert!(!config.providers.cloud_opt_in);
    let plex = config.plex.unwrap();
    assert_eq!(plex.url, "http://plex.example.invalid:32400");
    assert_eq!(plex.server_id, "synthetic-server");
    assert_eq!(
        plex.owner_token.resolve("plex").unwrap().expose(),
        "synthetic-plex-token"
    );
    let arr = &config.arr[0];
    assert_eq!(arr.kind, ArrKind::Sonarr);
    assert_eq!(arr.url, "http://sonarr.example.invalid:8989");
    assert_eq!(arr.id, "primary");
    assert_eq!(arr.libraries, ["7"]);
    assert_eq!(
        arr.api_key.resolve("arr").unwrap().expose(),
        "synthetic-arr-key"
    );
    let control = config
        .engine
        .control_secret
        .unwrap()
        .resolve("control")
        .unwrap();
    let webhook = arr
        .webhook_secret
        .as_ref()
        .unwrap()
        .resolve("webhook")
        .unwrap();
    assert_eq!(control.expose().len(), 64);
    assert!(
        control
            .expose()
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit())
    );
    assert_eq!(webhook.expose().len(), 64);
    assert_ne!(webhook.expose(), control.expose());
    assert!(!control.expose().bytes().all(|byte| byte == b'0'));
    for path in [output.clone(), output.join("state"), output.join("secrets")] {
        assert_eq!(
            fs::metadata(path).unwrap().permissions().mode() & 0o777,
            0o700
        );
    }
    for suffix in [
        "pitcrew.toml",
        "secrets/plex-token",
        "secrets/arr-api-key",
        "secrets/control",
        "secrets/arr-webhook",
    ] {
        assert_eq!(
            fs::metadata(output.join(suffix))
                .unwrap()
                .permissions()
                .mode()
                & 0o777,
            0o600
        );
    }
    assert!(!output.join("state/pitcrew.sqlite").exists());
}

#[test]
fn container_paths_are_separate_from_local_doctor_references() {
    let temp = tempfile::tempdir().unwrap();
    let (mut flags, output) = fixture(temp.path());
    flags.extend(args(&[
        "--runtime-root",
        "/config",
        "--connectivity",
        "--library",
        "8",
        "--public-origin",
        "https://help.example.invalid",
    ]));
    let install = pitcrew_setup::create(options(&flags), &mut empty()).unwrap();
    assert!(install.connectivity);
    let local = install.local_config;
    assert_eq!(local.database, output.join("state/pitcrew.sqlite"));
    assert_eq!(
        local
            .plex
            .unwrap()
            .owner_token
            .resolve("plex")
            .unwrap()
            .expose(),
        "synthetic-plex-token"
    );
    assert_eq!(
        local.arr[0].api_key.resolve("arr").unwrap().expose(),
        "synthetic-arr-key"
    );
    assert_eq!(
        local.stack.web_public_origin,
        "https://help.example.invalid"
    );
    let config = Config::parse(&fs::read_to_string(output.join("pitcrew.toml")).unwrap()).unwrap();
    assert_eq!(config.database, Path::new("/config/state/pitcrew.sqlite"));
    assert_eq!(
        config.plex.unwrap().owner_token.file.unwrap(),
        Path::new("/config/secrets/plex-token")
    );
    assert_eq!(config.arr[0].libraries, ["7", "8"]);
}

#[test]
fn prompts_only_for_missing_inputs_and_marks_credentials_secret() {
    let temp = tempfile::tempdir().unwrap();
    let output = temp.path().join("interactive");
    let flags = args(&[
        "--output",
        output.to_str().unwrap(),
        "--plex-url",
        "http://plex.example.invalid",
    ]);
    let mut inputs = Inputs(
        [
            ("server", false),
            ("radarr", false),
            ("http://radarr.example.invalid", false),
            ("3", false),
            ("synthetic-plex", true),
            ("synthetic-arr", true),
        ]
        .into_iter()
        .map(|(value, secret)| (value.into(), secret))
        .collect(),
    );
    let install = pitcrew_setup::create(options(&flags), &mut inputs).unwrap();
    assert!(inputs.0.is_empty());
    assert_eq!(install.local_config.arr[0].kind, ArrKind::Radarr);
    assert_eq!(
        install
            .local_config
            .plex
            .unwrap()
            .owner_token
            .resolve("plex")
            .unwrap()
            .expose(),
        "synthetic-plex"
    );
    assert_eq!(
        install.local_config.arr[0]
            .api_key
            .resolve("arr")
            .unwrap()
            .expose(),
        "synthetic-arr"
    );
}

#[test]
fn existing_installations_and_symlinks_are_never_overwritten() {
    let temp = tempfile::tempdir().unwrap();
    let (flags, output) = fixture(temp.path());
    fs::create_dir(&output).unwrap();
    fs::write(output.join("keep"), "unchanged").unwrap();
    assert_eq!(
        pitcrew_setup::create(options(&flags), &mut empty())
            .err()
            .unwrap(),
        "init: output directory already exists; choose a new directory"
    );
    assert_eq!(
        fs::read_to_string(output.join("keep")).unwrap(),
        "unchanged"
    );
    fs::remove_file(output.join("keep")).unwrap();
    fs::remove_dir(&output).unwrap();
    std::os::unix::fs::symlink(temp.path().join("missing"), &output).unwrap();
    assert!(pitcrew_setup::create(options(&flags), &mut empty()).is_err());
    assert!(!temp.path().join("missing").exists());
}

#[test]
fn invalid_or_missing_inputs_leave_no_output_and_do_not_echo_values() {
    let temp = tempfile::tempdir().unwrap();
    let (base, output) = fixture(temp.path());
    let credential_url = ["http://secret", "example.invalid"].join("@");
    for (flag, replacement) in [
        ("--plex-url", credential_url.as_str()),
        ("--arr-url", "http://example.invalid/?secret"),
        ("--plex-server-id", " "),
        ("--arr-kind", "secret"),
        ("--library", " "),
        ("--plex-token-file", "missing-secret"),
    ] {
        let mut flags = base.clone();
        let index = flags.iter().position(|value| value == flag).unwrap();
        flags[index + 1] = replacement.into();
        let error = pitcrew_setup::create(options(&flags), &mut empty())
            .err()
            .unwrap();
        assert!(!error.contains(&credential_url));
        assert!(!error.contains("missing-secret"));
        assert!(!output.exists());
    }
    let mut flags = base.clone();
    flags.extend(args(&["--runtime-root", "relative"]));
    assert_eq!(
        pitcrew_setup::create(options(&flags), &mut empty())
            .err()
            .unwrap(),
        "init: --runtime-root must be an absolute path"
    );
    for flag in [
        "--plex-url",
        "--plex-server-id",
        "--arr-kind",
        "--arr-url",
        "--library",
        "--plex-token-file",
        "--arr-api-key-file",
    ] {
        let mut flags = base.clone();
        let index = flags.iter().position(|value| value == flag).unwrap();
        flags.drain(index..index + 2);
        assert!(
            pitcrew_setup::create(options(&flags), &mut empty()).is_err(),
            "{flag}"
        );
        assert!(!output.exists());
    }
}

#[test]
fn credential_boundaries_and_control_characters_are_checked_before_writes() {
    let temp = tempfile::tempdir().unwrap();
    let (flags, output) = fixture(temp.path());
    for value in [
        "".to_owned(),
        " ".into(),
        "x y".into(),
        "x\ty".into(),
        "x\ny".into(),
        "x\0y".into(),
        "é".into(),
        "\u{7f}".into(),
        "x".repeat(4097),
    ] {
        fs::write(temp.path().join("token-input"), value).unwrap();
        assert!(pitcrew_setup::create(options(&flags), &mut empty()).is_err());
        assert!(!output.exists());
    }
    fs::write(temp.path().join("token-input"), "!".repeat(4096)).unwrap();
    fs::write(temp.path().join("key-input"), "~").unwrap();
    let config = pitcrew_setup::create(options(&flags), &mut empty())
        .unwrap()
        .local_config;
    assert_eq!(
        config
            .plex
            .unwrap()
            .owner_token
            .resolve("plex")
            .unwrap()
            .expose()
            .len(),
        4096
    );
    assert_eq!(config.arr[0].api_key.resolve("arr").unwrap().expose(), "~");
}

