struct Labels(VecDeque<(String, bool)>, Vec<String>);
impl Prompt for Labels {
    fn read(&mut self, label: &str, secret: bool) -> pitcrew_setup::Result<String> {
        self.1.push(label.into());
        let (value, expected_secret) = self.0.pop_front().expect("unexpected prompt");
        assert_eq!(secret, expected_secret);
        Ok(value)
    }
}

#[test]
fn interactive_discover_lists_sanitized_sections_and_asks_for_token_once() {
    let temp = tempfile::tempdir().unwrap();
    let output = temp.path().join("installation");
    let flags = args(&["--discover", "--output", output.to_str().unwrap()]);
    let mut prompt = Labels(
        VecDeque::from([
            ("http://plex.example.invalid:32400".to_string(), false),
            ("synthetic-plex-token".to_string(), true),
            ("radarr".to_string(), false),
            ("http://radarr.example.invalid:7878".to_string(), false),
            ("3".to_string(), false),
            ("synthetic-arr-key".to_string(), true),
        ]),
        vec![],
    );
    pitcrew_setup::create_with(options(&flags), &mut prompt, &mut fake_server()).unwrap();
    assert!(prompt.0.is_empty());
    let library = prompt.1.iter().find(|l| l.contains("section key")).unwrap();
    assert_eq!(
        library,
        "Plex library section key for this manager (3 Films[2J [movie], 9 Shows [show])"
    );
    assert_eq!(
        prompt
            .1
            .iter()
            .filter(|l| l.contains("Plex owner token"))
            .count(),
        1
    );
    assert!(!prompt.1.iter().any(|l| l.contains("machineIdentifier")));
}
